import { createHash } from 'node:crypto';

const isReactRefreshPreamble = (attributes, source) =>
  /\btype\s*=\s*(['"])module\1/i.test(attributes) &&
  !/\bsrc\s*=/i.test(attributes) &&
  source.includes('injectIntoGlobalHook(window);') &&
  source.includes('window.$RefreshReg$') &&
  source.includes('window.$RefreshSig$');
const isViteClient = (attributes) =>
  /\btype\s*=\s*(['"])module\1/i.test(attributes) &&
  /\bsrc\s*=\s*(['"])\/?@vite\/client(?:\?[^'"]*)?\1/i.test(attributes);

function addScriptHash(policy, hash) {
  const directives = policy.split(';');
  const index = directives.findIndex((directive) =>
    /^\s*script-src\s/i.test(directive),
  );
  if (index < 0)
    throw new Error('The development CSP has no script-src directive for the React Refresh preamble.');

  const directive = directives[index];
  const source = `'sha256-${hash}'`;
  if (!directive.split(/\s+/).includes(source))
    directives[index] = `${directive.trimEnd()} ${source}`;
  return directives.join(';');
}

/** Add a hash only for the known inline preamble generated by plugin-react. */
export function addReactRefreshPreambleHash(html) {
  const scripts = [],
    scriptPattern = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
  for (const match of html.matchAll(scriptPattern)) {
    const [, attributes, source] = match;
    if (!isReactRefreshPreamble(attributes, source) && !isViteClient(attributes))
      continue;
    scripts.push({
      tag: match[0],
      start: match.index,
      hash: isReactRefreshPreamble(attributes, source)
        ? createHash('sha256').update(source.replace(/\r\n?/g, '\n'), 'utf8').digest('base64')
        : undefined,
    });
  }
  if (!scripts.length) return html;
  const originalCsp = /<meta\b[^>]*\bhttp-equiv\s*=\s*(['"])Content-Security-Policy\1[^>]*>/i.exec(html);
  if (!originalCsp)
    throw new Error('Could not find the page CSP meta tag before Vite development scripts.');
  const originalCspEnd = originalCsp.index + originalCsp[0].length;
  const earlyScripts = scripts.filter(({ start }) => start < originalCspEnd);
  let output = html;
  for (const { start, tag } of [...earlyScripts].reverse())
    output = `${output.slice(0, start)}${output.slice(start + tag.length)}`;

  let foundCsp = false;
  output = output.replace(/<meta\b[^>]*>/gi, (meta) => {
    if (foundCsp || !/\bhttp-equiv\s*=\s*(['"])Content-Security-Policy\1/i.test(meta))
      return meta;
    const contentMatch = meta.match(/\bcontent\s*=\s*(['"])(.*?)\1/i);
    if (!contentMatch) return meta;
    const nextPolicy = scripts.reduce(
      (policy, script) => script.hash ? addScriptHash(policy, script.hash) : policy,
      contentMatch[2],
    );
    foundCsp = true;
    return meta.replace(contentMatch[0], `content=${contentMatch[1]}${nextPolicy}${contentMatch[1]}`);
  });
  if (!foundCsp)
    throw new Error('Could not find the page CSP meta tag before Vite development scripts.');
  if (!earlyScripts.length) return output;
  const cspTag = /<meta\b[^>]*\bhttp-equiv\s*=\s*(['"])Content-Security-Policy\1[^>]*>/i.exec(output);
  const insertAt = cspTag.index + cspTag[0].length;
  return `${output.slice(0, insertAt)}\n${earlyScripts.map(({ tag }) => tag).join('\n')}\n${output.slice(insertAt)}`;
}

/** Vite serves this plugin only in development; production CSP stays source-defined. */
/** @returns {import('vite').Plugin} */
export function reactRefreshCspPlugin() {
  return {
    name: 'noteboard-dev-react-refresh-csp',
    apply: 'serve',
    transformIndexHtml: {
      order: 'post',
      /** @param {string} html */
      handler(html) {
        return addReactRefreshPreambleHash(html);
      },
    },
  };
}
